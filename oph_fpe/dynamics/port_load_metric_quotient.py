def _canonical_bytes(value: Any) -> bytes:
    return json.dumps(
        value,
        sort_keys=True,
        separators=(",", ":"),
        ensure_ascii=True,
        allow_nan=False,
    ).encode("ascii")


def _sha(value: Any) -> str:
    return "sha256:" + hashlib.sha256(_canonical_bytes(value)).hexdigest()


def _raw_pin(path: Path) -> dict[str, Any]:
    raw = path.read_bytes()
    return {
        "path": path.relative_to(ROOT).as_posix(),
        "bytes": len(raw),
        "sha256": "sha256:" + hashlib.sha256(raw).hexdigest(),
    }


def _strict_object(pairs: list[tuple[str, Any]]) -> dict[str, Any]:
    result: dict[str, Any] = {}
    for key, value in pairs:
        if key in result:
            raise PortLoadQuotientError(f"duplicate JSON key: {key}")
        result[key] = value
    return result


def _reject_nonfinite(value: str) -> None:
    raise PortLoadQuotientError(f"non-finite JSON constant is forbidden: {value}")


def load_json_strict(path: Path) -> dict[str, Any]:
    try:
        result = json.loads(
            path.read_text(encoding="utf-8"),
            object_pairs_hook=_strict_object,
            parse_constant=_reject_nonfinite,
        )
    except (OSError, UnicodeDecodeError, json.JSONDecodeError) as error:
        raise PortLoadQuotientError(f"cannot load {path}: {error}") from error
    if not isinstance(result, dict):
        raise PortLoadQuotientError(f"{path} is not a JSON object")
    return result


def _validated_self_digest(path: Path, schema: str) -> dict[str, Any]:
    receipt = load_json_strict(path)
    payload = copy.deepcopy(receipt)
    digest = payload.pop("receipt_sha256", None)
    if digest != _sha(payload) or receipt.get("schema") != schema:
        raise PortLoadQuotientError(f"parent contract drifted: {path}")
    return receipt


