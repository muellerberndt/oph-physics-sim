def write_receipt(path: Path = DEFAULT_RECEIPT) -> dict[str, Any]:
    receipt = produce_receipt()
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(receipt, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    return receipt


