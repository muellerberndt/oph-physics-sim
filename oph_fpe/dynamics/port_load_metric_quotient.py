def _difference_matrix(
    positive: Sequence[int], antipodes: Sequence[int]
) -> list[list[int]]:
    matrix = [[0] * 12 for _ in range(6)]
    for row, port in enumerate(positive):
        matrix[row][port] = 1
        matrix[row][antipodes[port]] = -1
    return matrix


def _matmul(
    left: Sequence[Sequence[Any]], right: Sequence[Sequence[Any]]
) -> list[list[Any]]:
    return [
        [sum((left[i][k] * right[k][j] for k in range(len(right))), 0) for j in range(len(right[0]))]
        for i in range(len(left))
    ]


def _qmatmul(
    left: Sequence[Sequence[Q5]], right: Sequence[Sequence[Q5]]
) -> list[list[Q5]]:
    output = []
    for i in range(len(left)):
        row = []
        for j in range(len(right[0])):
            value = ZERO
            for k in range(len(right)):
                value = _qadd(value, _qmul(left[i][k], right[k][j]))
            row.append(value)
        output.append(row)
    return output


def _transpose(matrix: Sequence[Sequence[Any]]) -> list[list[Any]]:
    return [list(column) for column in zip(*matrix, strict=True)]


def _rational_matrix_product(
    left: Sequence[Sequence[Fraction]], right: Sequence[Sequence[Fraction]]
) -> list[list[Fraction]]:
    return [
        [
            sum((left[i][k] * right[k][j] for k in range(len(right))), Fraction())
            for j in range(len(right[0]))
        ]
        for i in range(len(left))
    ]


def _determinant_integer(matrix: Sequence[Sequence[int]]) -> int:
    work = [[Fraction(value) for value in row] for row in matrix]
    sign = 1
    determinant = Fraction(1)
    for column in range(len(work)):
        pivot = next(
            (row for row in range(column, len(work)) if work[row][column]), None
        )
        if pivot is None:
            return 0
        if pivot != column:
            work[column], work[pivot] = work[pivot], work[column]
            sign *= -1
        diagonal = work[column][column]
        determinant *= diagonal
        for row in range(column + 1, len(work)):
            factor = work[row][column] / diagonal
            for index in range(column, len(work)):
                work[row][index] -= factor * work[column][index]
    value = sign * determinant
    if value.denominator != 1:
        raise PortLoadQuotientError("integer matrix has nonintegral determinant")
    return value.numerator


def _compositions(total: int, slots: int) -> list[tuple[int, ...]]:
    output: list[tuple[int, ...]] = []

    def visit(remaining: int, index: int, row: tuple[int, ...]) -> None:
        if index == slots - 1:
            output.append(row + (remaining,))
            return
        for value in range(remaining + 1):
            visit(remaining - value, index + 1, row + (value,))

    visit(total, 0, ())
    return output


def _apply_difference(matrix: Sequence[Sequence[int]], state: Sequence[int]) -> tuple[int, ...]:
    return tuple(sum(row[index] * state[index] for index in range(12)) for row in matrix)


def _formula_image(total: int) -> set[tuple[int, ...]]:
    return {
        value
        for value in itertools.product(range(-total, total + 1), repeat=6)
        if sum(abs(item) for item in value) <= total
        and (sum(value) - total) % 2 == 0
    }


def _balanced_outcome(state: Sequence[int], left: int, right: int) -> tuple[int, ...]:
    output = list(state)
    total = state[left] + state[right]
    output[left] = total // 2
    output[right] = total - output[left]
    return tuple(output)


def _quotient_distribution(
    state: Sequence[int], edges: Sequence[tuple[int, int]], difference: Sequence[Sequence[int]]
) -> dict[tuple[int, ...], Fraction]:
    output: dict[tuple[int, ...], Fraction] = {}
    for left, right in edges:
        for directed_left, directed_right in ((left, right), (right, left)):
            target = _balanced_outcome(state, directed_left, directed_right)
            quotient = _apply_difference(difference, target)
            output[quotient] = output.get(quotient, Fraction()) + Fraction(1, 60)
    return output


def _distribution_rows(distribution: Mapping[tuple[int, ...], Fraction]) -> list[dict[str, Any]]:
    return [
        {
            "z": list(value),
            "probability": f"{probability.numerator}/{probability.denominator}",
        }
        for value, probability in sorted(distribution.items())
    ]


def _expectation(distribution: Mapping[tuple[int, ...], Fraction]) -> tuple[Fraction, ...]:
    return tuple(
        sum((probability * value[index] for value, probability in distribution.items()), Fraction())
        for index in range(6)
    )


