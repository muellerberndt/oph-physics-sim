def control_truncated_series() -> dict[str, Any]:
    """A series too short to verify the channel property must refuse."""

    series = measure_response_series()[:2]
    try:
        extract_pole_residues(series)
    except ChargedResponseError as error:
        return {
            "expected_failure": True,
            "failed": True,
            "code": error.code,
        }
    return {"expected_failure": True, "failed": False}


def control_doctored_step() -> dict[str, Any]:
    """A perturbed one-step map must fail lattice reconstruction or the
    exactness gates; a silent pass is forbidden."""

    series = measure_response_series()
    doctored = [sample.copy() for sample in series]
    doctored[1][0, 0] += 1.0e-3
    try:
        extract_pole_residues(doctored)
    except ChargedResponseError as error:
        return {
            "expected_failure": True,
            "failed": True,
            "code": error.code,
        }
    return {"expected_failure": True, "failed": False}


def control_lattice_near_miss() -> dict[str, Any]:
    """A value near, but off, the exact lattice must be refused rather than
    rounded."""

    off_lattice = (10.0 + 2.0 * SQRT5) / RESIDUE_SCALE + 20.0 * RECONSTRUCTION_TOLERANCE
    try:
        reconstruct_q5(off_lattice, RESIDUE_SCALE)
    except ChargedResponseError as error:
        return {
            "expected_failure": True,
            "failed": True,
            "code": error.code,
        }
    return {"expected_failure": True, "failed": False}


def control_swapped_residues(carrier: Mapping[str, Any]) -> dict[str, Any]:
    """Swapping the frame and kernel residues must be detected by the
    exactness gate as the Galois partner."""

    exact = isotypic_projectors(carrier["adjacency"])
    measured = measured_in_carrier_order(carrier)
    swapped = measured["kernel"]["projector_exact"]
    matches_frame = all(
        (swapped[i][j] - exact["frame"][i][j]).is_zero()
        for i in range(PORTS)
        for j in range(PORTS)
    )
    try:
        _require(
            matches_frame,
            "RESIDUE_SWAP_DETECTED",
            "the kernel residue is not the frame projector",
        )
    except ChargedResponseError as error:
        return {
            "expected_failure": True,
            "failed": True,
            "code": error.code,
        }
    return {"expected_failure": True, "failed": False}


