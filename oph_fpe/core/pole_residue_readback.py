"""Pole-residue readback of the propagated screen response (issue #569).

The simulator's local channel is the unitary one-step map generated by the
icosahedral coupling.  This module measures the two-point response of that
channel from propagated impulse states, extracts its pole structure, and
reconstructs the residues on the exact Z[sqrt5] lattice with fail-closed
tolerance and uniqueness gates.  The measured statements:

* the response has exactly four pole clusters, whose reconstructed exact
  locations are the Laplacian band costs 0, 5 - sqrt5, 6, 5 + sqrt5 with
  multiplicities 1, 3, 3, 5;
* the residue at the minimal positive pole has measured rank exactly three
  and reconstructs exactly to the frame-band projector: the measured family
  fiber is the slowest-relaxing nonconstant mode of the propagated dynamics;
* the reconstructed residue is primitive (it equals one exact band
  projector), its rotation action is faithful (kernel order one over the
  sixty incidence automorphisms), and Galois conjugation carries it to the
  kernel-band residue at the maximal pole.

CLAIM BOUNDARY.  This is the pole-residue object of the response resolvent
of the propagated screen dynamics, realized inside the screen coefficient
space.  It is not a matter-pole measurement: chirality and spin data, the
matter-pole identification, and laboratory current attachment are open on
issue #569.  External multiplicity copies remain invisible to the screen
response; that boundary is the #617 theorem and is restated here, not
defeated.  The artifact stores exact reconstructed values and booleans
only; no floating-point number enters the payload.
"""

