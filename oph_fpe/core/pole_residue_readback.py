def _module_sha256(path: Path) -> str:
    return "sha256:" + hashlib.sha256(path.read_bytes()).hexdigest()


def produce_pole_residue_artifact(
    carrier_manifest: Mapping[str, Any], parent_artifact: Mapping[str, Any]
) -> dict[str, Any]:
    carrier = load_carrier(carrier_manifest)
    carrier_sha = canonical_sha256(dict(carrier_manifest))
    _require(
        parent_artifact["carrier_binding"]["carrier_manifest_sha256"] == carrier_sha,
        "PARENT_CARRIER",
        "the parent response artifact must bind the same carrier manifest",
    )

    readback = certify_pole_residue_readback(carrier)
    controls = {
        "truncated_series": control_truncated_series(),
        "doctored_step": control_doctored_step(),
        "lattice_near_miss": control_lattice_near_miss(),
        "swapped_residues": control_swapped_residues(carrier),
    }
    for name, verdict in controls.items():
        _require(
            verdict["expected_failure"] is True and verdict["failed"] is True,
            "CONTROL_NOT_FAILED",
            f"control {name} did not record its required failure",
        )

    payload: dict[str, Any] = {
        "schema": ARTIFACT_SCHEMA,
        "issue": 569,
        "claim_boundary": (
            "Measured pole-residue object of the response resolvent of the "
            "propagated screen dynamics, realized inside the screen "
            "coefficient space: four pole clusters at the exact band costs, "
            "with the rank-three frame residue at the minimal positive pole. "
            "This is not a matter-pole measurement; chirality and spin data, "
            "matter-pole identification, and laboratory attachment are open. "
            "External multiplicity copies remain invisible to the screen "
            "response per the standing invisibility theorem."
        ),
        "carrier_binding": {
            "carrier_manifest_sha256": carrier_sha,
            "parent_artifact_sha256": parent_artifact["artifact_sha256"],
        },
        "dynamics_binding": {
            "dynamics_module": "oph_fpe.core.echosahedral_dynamics",
            "dynamics_sha256": _module_sha256(Path(_dynamics_module.__file__)),
            "generator": "icosahedral coupling (the graph Laplacian) under the unitary one-step channel",
        },
        "pole_residue_readback": readback,
        "controls": controls,
    }
    payload["artifact_sha256"] = "sha256:" + canonical_sha256(payload)
    return payload


def write_pole_residue_artifact(
    carrier_manifest_path: Path, parent_artifact_path: Path, output_path: Path
) -> dict[str, Any]:
    manifest = json.loads(carrier_manifest_path.read_text(encoding="utf-8"))
    parent = json.loads(parent_artifact_path.read_text(encoding="utf-8"))
    artifact = produce_pole_residue_artifact(manifest, parent)
    output_path.write_text(
        json.dumps(artifact, indent=2, sort_keys=True) + "\n", encoding="utf-8"
    )
    return artifact


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--carrier-manifest", type=Path, required=True)
    parser.add_argument("--parent-artifact", type=Path, required=True)
    parser.add_argument("--out", type=Path, required=True)
    args = parser.parse_args()
    artifact = write_pole_residue_artifact(
        args.carrier_manifest, args.parent_artifact, args.out
    )
    print(
        json.dumps(
            {
                "artifact_sha256": artifact["artifact_sha256"],
                "family_band_residue": artifact["pole_residue_readback"][
                    "family_band_residue"
                ],
            },
            indent=2,
        )
    )
    return 0


