"""Exact control against identifying seam repair with a port-current algebra.

The scalar A2 seam law supplies thirty conditional equalizers

    E_e = I - (1/2) b_e b_e^T

on the twelve port readings.  Every ``b_e`` has coordinate sum zero, so the
disagreement generators ``G_e = 2(I-E_e) = b_e b_e^T`` act on the
eleven-dimensional zero-sum space ``V_0``.

This module computes three target-independent closure facts:

* the nonzero first commutators ``[G_e,G_f]`` span dimension 49;
* their Lie closure is the full metric-skew algebra ``so(V_0)``, dimension 55;
* the unital operator algebra generated by the equalizers is
  ``End(V_0)``, dimension 121.

All matrices are integral in the fixed basis ``e_i-e_11``.  Ranks are checked
by exact rational elimination and independently modulo two declared primes.
The dimension-55 identification also has a structural upper bound because
every commutator is skew for the positive Gram matrix of that basis.

The result is a negative control on one proposed bridge, not a negative result
about OPH.  It excludes relabeling the scalar repair equalizers as the desired
twelve-dimensional compact current.  A separate reversible-response and
same-current holonomy producer remains necessary.
"""

from __future__ import annotations

import argparse
import copy
