def verify_report(report: Mapping[str, Any]) -> dict[str, Any]:
    """Recompute the report and reject any semantic or byte-level mutation."""

    expected = build_report()
    supplied = copy.deepcopy(dict(report))
    passed = supplied == expected
    return {
        "schema": "oph.seam-equalizer-current-control-verification/1.0.0",
        "passed": passed,
        "expected_report_sha256": expected["report_sha256"],
        "supplied_report_sha256": supplied.get("report_sha256"),
        "reason": (
            "byte-exact semantic replay matched"
            if passed
            else "supplied report differs from exact recomputation"
        ),
    }


def render_report(report: Mapping[str, Any]) -> str:
    return json.dumps(report, indent=2, sort_keys=True) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path)
    parser.add_argument("--verify", type=Path)
    args = parser.parse_args()
    if args.verify is not None:
        supplied = json.loads(args.verify.read_text(encoding="utf-8"))
        verification = verify_report(supplied)
        print(render_report(verification), end="")
        return 0 if verification["passed"] else 1
    report = build_report()
    rendered = render_report(report)
    if args.out is None:
        print(rendered, end="")
    else:
        args.out.parent.mkdir(parents=True, exist_ok=True)
        args.out.write_text(rendered, encoding="utf-8")
    return 0


