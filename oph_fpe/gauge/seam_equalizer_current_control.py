import hashlib
import json
from pathlib import Path
from typing import Any, Iterable, Mapping, Sequence

from oph_fpe.dynamics.self_readback_repair_closure import (
    ORIENTED_BASE_FACES,
    PORT_COUNT,
    exact_reference_edges,
)


SCHEMA = "oph.seam-equalizer-current-control/1.0.0"
STATUS = "ATTAINED_NEGATIVE_CONTROL"
ZERO_SUM_DIMENSION = PORT_COUNT - 1
RANK_PRIMES = (1_000_003, 1_000_033)

Matrix = tuple[tuple[int, ...], ...]


def _canonical_bytes(value: Mapping[str, Any] | Sequence[Any]) -> bytes:
    return json.dumps(
        value,
        sort_keys=True,
        separators=(",", ":"),
        ensure_ascii=True,
    ).encode("ascii")


def _sha256(value: Mapping[str, Any] | Sequence[Any]) -> str:
    return "sha256:" + hashlib.sha256(_canonical_bytes(value)).hexdigest()


def _identity(dimension: int) -> Matrix:
    return tuple(
        tuple(int(row == column) for column in range(dimension))
        for row in range(dimension)
    )


def _transpose(matrix: Matrix) -> Matrix:
    return tuple(
        tuple(matrix[row][column] for row in range(len(matrix)))
        for column in range(len(matrix[0]))
    )


def _matrix_add(left: Matrix, right: Matrix) -> Matrix:
    return tuple(
        tuple(
            left[row][column] + right[row][column]
            for column in range(len(left[0]))
        )
        for row in range(len(left))
    )


def _matrix_subtract(left: Matrix, right: Matrix) -> Matrix:
    return tuple(
        tuple(
            left[row][column] - right[row][column]
            for column in range(len(left[0]))
        )
        for row in range(len(left))
    )


def _matrix_multiply(left: Matrix, right: Matrix) -> Matrix:
    inner = len(right)
    return tuple(
        tuple(
            sum(
                left[row][index] * right[index][column]
                for index in range(inner)
            )
            for column in range(len(right[0]))
        )
        for row in range(len(left))
    )


def _commutator(left: Matrix, right: Matrix) -> Matrix:
    return _matrix_subtract(
        _matrix_multiply(left, right),
        _matrix_multiply(right, left),
    )


def _flatten(matrix: Matrix) -> tuple[int, ...]:
    return tuple(entry for row in matrix for entry in row)


def _is_zero(matrix: Matrix) -> bool:
    return not any(_flatten(matrix))


def zero_sum_basis() -> Matrix:
    """Return the columns ``e_0-e_11, ..., e_10-e_11``."""

    return tuple(
        tuple(
            int(row == column) - int(row == ZERO_SUM_DIMENSION)
            for column in range(ZERO_SUM_DIMENSION)
        )
        for row in range(PORT_COUNT)
    )


def zero_sum_gram_matrix() -> Matrix:
    """Return the positive Gram matrix of :func:`zero_sum_basis`."""

    basis = zero_sum_basis()
    return _matrix_multiply(_transpose(basis), basis)


def _restrict_zero_sum(full_operator: Matrix) -> Matrix:
    """Represent a sum-preserving full operator in the fixed zero-sum basis."""

    basis = zero_sum_basis()
    image = _matrix_multiply(full_operator, basis)
    # A vector B*y has its first eleven coordinates equal to y.  Every seam
    # generator preserves V_0, so these rows are the exact restricted matrix.
    return tuple(image[row] for row in range(ZERO_SUM_DIMENSION))


def seam_disagreement_generators() -> tuple[Matrix, ...]:
    """Return the thirty integral matrices ``G_e=b_e b_e^T`` on ``V_0``."""

    rows: list[Matrix] = []
    for left, right in exact_reference_edges():
        difference = [0] * PORT_COUNT
        difference[left] = 1
        difference[right] = -1
        full = tuple(
            tuple(difference[row] * difference[column] for column in range(PORT_COUNT))
            for row in range(PORT_COUNT)
        )
        rows.append(_restrict_zero_sum(full))
    return tuple(rows)


def first_nonzero_commutators(
    generators: Sequence[Matrix] | None = None,
) -> tuple[Matrix, ...]:
    """Return all nonzero unordered first commutators in canonical order."""

    source = tuple(generators or seam_disagreement_generators())
    rows: list[Matrix] = []
    for left_index in range(len(source)):
        for right_index in range(left_index):
            candidate = _commutator(
                source[left_index],
                source[right_index],
            )
            if not _is_zero(candidate):
                rows.append(candidate)
    return tuple(rows)


def exact_rational_rank(matrices: Sequence[Matrix]) -> int:
    """Compute the exact row rank of flattened integer matrices over Q."""

    if not matrices:
        return 0
    rows = [
        [Fraction(value) for value in _flatten(matrix)]
        for matrix in matrices
    ]
    row_count = len(rows)
    column_count = len(rows[0])
    rank = 0
    column = 0
    while rank < row_count and column < column_count:
        pivot = next(
            (
                candidate
                for candidate in range(rank, row_count)
                if rows[candidate][column]
            ),
            None,
        )
        if pivot is None:
            column += 1
            continue
        rows[rank], rows[pivot] = rows[pivot], rows[rank]
        pivot_value = rows[rank][column]
        for position in range(column, column_count):
            rows[rank][position] /= pivot_value
        for candidate in range(rank + 1, row_count):
            factor = rows[candidate][column]
            if not factor:
                continue
            for position in range(column, column_count):
                rows[candidate][position] -= factor * rows[rank][position]
        rank += 1
        column += 1
    return rank


class _ModularBasis:
    """Deterministic incremental row basis over one prime field."""

    def __init__(self, prime: int) -> None:
        self.prime = int(prime)
        self._rows: dict[int, tuple[int, ...]] = {}

    @property
    def rank(self) -> int:
        return len(self._rows)

    def add(self, values: Iterable[int]) -> bool:
        row = [int(value) % self.prime for value in values]
        for pivot, basis_row in self._rows.items():
            factor = row[pivot]
            if factor:
                row = [
                    (value - factor * base) % self.prime
                    for value, base in zip(row, basis_row, strict=True)
                ]
        pivot = next(
            (position for position, value in enumerate(row) if value),
            None,
        )
        if pivot is None:
            return False
        inverse = pow(row[pivot], self.prime - 2, self.prime)
        normalized = tuple((value * inverse) % self.prime for value in row)
        self._rows[pivot] = normalized
        self._rows = dict(sorted(self._rows.items()))
        return True


def modular_rank(matrices: Sequence[Matrix], prime: int) -> int:
    basis = _ModularBasis(prime)
    for matrix in matrices:
        basis.add(_flatten(matrix))
    return basis.rank


def _independent_modular_basis(
    matrices: Sequence[Matrix],
    prime: int,
) -> tuple[list[Matrix], _ModularBasis]:
    reducer = _ModularBasis(prime)
    selected: list[Matrix] = []
    for matrix in matrices:
        if reducer.add(_flatten(matrix)):
            selected.append(matrix)
    return selected, reducer


def metric_self_adjoint(matrix: Matrix, gram: Matrix | None = None) -> bool:
    metric = gram or zero_sum_gram_matrix()
    return _matrix_multiply(metric, matrix) == _matrix_multiply(
        _transpose(matrix),
        metric,
    )


def metric_skew(matrix: Matrix, gram: Matrix | None = None) -> bool:
    metric = gram or zero_sum_gram_matrix()
    return _is_zero(
        _matrix_add(
            _matrix_multiply(metric, matrix),
            _matrix_multiply(_transpose(matrix), metric),
        )
    )


def compact_commutator_closure(
    seed: Sequence[Matrix],
    *,
    prime: int = RANK_PRIMES[0],
) -> tuple[tuple[Matrix, ...], tuple[int, ...]]:
    """Close an H-skew seed under brackets using exact integer matrices."""

    selected, reducer = _independent_modular_basis(seed, prime)
    round_ranks = [len(selected)]
    while True:
        previous_rank = len(selected)
        snapshot = tuple(selected)
        for left_index in range(len(snapshot)):
            for right_index in range(left_index):
                candidate = _commutator(
                    snapshot[left_index],
                    snapshot[right_index],
                )
                if reducer.add(_flatten(candidate)):
                    selected.append(candidate)
        round_ranks.append(len(selected))
        if len(selected) == previous_rank:
            break
        if len(selected) > ZERO_SUM_DIMENSION * (ZERO_SUM_DIMENSION - 1) // 2:
            raise ValueError("metric-skew closure exceeded its structural upper bound")
    return tuple(selected), tuple(round_ranks)


def generated_operator_algebra(
    generators: Sequence[Matrix],
    *,
    prime: int = RANK_PRIMES[0],
) -> tuple[tuple[Matrix, ...], tuple[int, ...]]:
    """Return a modularly independent basis of the generated unital algebra."""

    identity = _identity(ZERO_SUM_DIMENSION)
    selected, reducer = _independent_modular_basis(
        (identity, *tuple(generators)),
        prime,
    )
    round_ranks = [len(selected)]
    upper_bound = ZERO_SUM_DIMENSION * ZERO_SUM_DIMENSION
    while True:
        previous_rank = len(selected)
        snapshot = tuple(selected)
        for current in snapshot:
            for generator in generators:
                for candidate in (
                    _matrix_multiply(current, generator),
                    _matrix_multiply(generator, current),
                ):
                    if reducer.add(_flatten(candidate)):
                        selected.append(candidate)
                    if len(selected) == upper_bound:
                        break
                if len(selected) == upper_bound:
                    break
            if len(selected) == upper_bound:
                break
        round_ranks.append(len(selected))
        if len(selected) in (previous_rank, upper_bound):
            break
    return tuple(selected), tuple(round_ranks)


